def test_cargo_lock_toml_reordered_keys_and_origin_provenance(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    root = minimal_tree(tmp_path)
    git_source = "git+https://example.invalid/org/dep?rev=deadbeef#deadbeefcafe"
    write_cargo_lock(
        root / "clients/desktop/src-tauri/Cargo.lock",
        [
            {
                "checksum": "a" * 64,
                "version": "1.4.0",
                "source": "registry+https://github.com/rust-lang/crates.io-index",
                "name": "reg-crate",
            },
            {"version": "0.2.0", "source": git_source, "name": "git-dep"},
            {"name": "path-dep", "version": "0.1.0"},
            {"name": "eurogas-nexus-desktop", "version": "0.5.0"},
        ],
    )

    packages, inputs = generate_sboms.collect_components(root=root)
    rust = {item["name"]: item for item in packages["desktop-rust"]}
    assert set(rust) == {"reg-crate", "git-dep", "path-dep"}
    assert rust["reg-crate"]["purl"] == "pkg:cargo/reg-crate@1.4.0"
    assert rust["reg-crate"]["checksum"] == "a" * 64
    assert rust["git-dep"]["origin"] == "git"
    assert "purl" not in rust["git-dep"]
    assert rust["path-dep"]["origin"] == "path"
    assert "purl" not in rust["path-dep"]

    cargo_input = next(item for item in inputs if item["component"] == "desktop-rust")
    assert cargo_input["origins"] == {
        "registry": 1,
        "registry-other": 0,
        "git": 1,
        "path": 1,
        "other": 0,
    }
    assert cargo_input["excluded_entries"] == [
        {
            "spec": "eurogas-nexus-desktop 0.5.0",
            "reason": "project-package",
            "name": "eurogas-nexus-desktop",
        }
    ]

    output = tmp_path / "sbom"
    assert generate(root, output, monkeypatch) == 0
    document = json.loads(
        (output / "eurogas-nexus-desktop-rust.spdx.json").read_text(encoding="utf-8")
    )
    by_name = {package["name"]: package for package in document["packages"]}
    assert by_name["reg-crate"]["checksums"] == [{"algorithm": "SHA256", "checksumValue": "a" * 64}]
    assert by_name["git-dep"]["sourceInfo"] == git_source
    locators = [
        ref["referenceLocator"]
        for package in document["packages"]
        for ref in package.get("externalRefs", [])
    ]
    # Only the crates.io crate carries a purl; git/path deps keep raw provenance.
    assert locators == ["pkg:cargo/reg-crate@1.4.0"]


def test_cargo_origin_requires_exact_canonical_crates_io_sources() -> None:
    assert (
        generate_sboms.cargo_origin("registry+https://github.com/rust-lang/crates.io-index")
        == "registry"
    )
    assert generate_sboms.cargo_origin("sparse+https://index.crates.io/") == "registry"
    assert generate_sboms.cargo_origin(None) == "path"
    assert generate_sboms.cargo_origin("git+https://example.invalid/org/dep") == "git"
    # Lookalike URLs that merely contain crates.io-index are not crates.io.
    for lookalike in (
        "registry+https://mirror.invalid/crates.io-index",
        "registry+https://github.com/rust-lang/crates.io-index/",
        "sparse+https://index.crates.io.invalid/",
        "sparse+https://index.crates.io",
    ):
        assert generate_sboms.cargo_origin(lookalike) == "registry-other", lookalike
    assert generate_sboms.cargo_origin("file:///srv/registry") == "other"


