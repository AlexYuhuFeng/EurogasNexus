def write_npm_lock(path: Path, packages: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(
            {"name": "fixture", "version": "0.0.0", "lockfileVersion": 3, "packages": packages}
        ),
        encoding="utf-8",
    )


def write_cargo_lock(path: Path, entries: list[dict[str, Any]]) -> None:
    blocks = []
    for entry in entries:
        lines = ["[[package]]"]
        for key, value in entry.items():
            if isinstance(value, list):
                lines.append(f"{key} = [{', '.join(json.dumps(item) for item in value)}]")
            else:
                lines.append(f"{key} = {json.dumps(value)}")
        blocks.append("\n".join(lines))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("version = 4\n\n" + "\n\n".join(blocks) + "\n", encoding="utf-8")


def minimal_tree(root: Path) -> Path:
    """Write a complete, valid fixture lock tree."""
    root.mkdir(parents=True, exist_ok=True)
    (root / "requirements-runtime.lock").write_text(DEFAULT_PYTHON_LOCK, encoding="utf-8")
    write_npm_lock(root / "clients/web/package-lock.json", DEFAULT_WEB_PACKAGES)
    write_npm_lock(root / "clients/desktop/package-lock.json", DEFAULT_DESKTOP_PACKAGES)
    write_cargo_lock(root / "clients/desktop/src-tauri/Cargo.lock", DEFAULT_CARGO_ENTRIES)
    return root


def generate(root: Path, output: Path, monkeypatch: pytest.MonkeyPatch) -> int:
    """Run the generator against a fixture tree instead of the repository root."""
    monkeypatch.setattr(generate_sboms, "ROOT", root)
    return generate_sboms.main(
        ["--output-dir", str(output), "--notices", str(output / "THIRD_PARTY_NOTICES.md")]
    )


def test_nested_npm_entries_keep_last_segment_and_scoped_names(tmp_path: Path) -> None:
    root = minimal_tree(tmp_path)
    write_npm_lock(
        root / "clients/web/package-lock.json",
        {
            "": {"name": "eurogas-nexus-web", "version": "0.5.0"},
            "node_modules/@scope/tool": {"version": "2.0.0", "license": "MIT"},
            "node_modules/@scope/tool/node_modules/dup": {"version": "1.0.0", "license": "ISC"},
            "node_modules/dup": {"version": "0.9.0"},
            "node_modules/alias-dir": {"name": "real-package", "version": "3.0.0"},
            "node_modules/plain": {"name": "not a valid npm name", "version": "1.0.0"},
            "node_modules/linked": {"resolved": "packages/linked", "link": True},
        },
    )

    web = generate_sboms.npm_packages(root / "clients/web/package-lock.json")

    identities = [(item["name"], item["version"]) for item in web.packages]
    assert ("@scope/tool", "2.0.0") in identities
    assert ("dup", "1.0.0") in identities
    assert ("dup", "0.9.0") in identities
    assert ("real-package", "3.0.0") in identities
    # An invalid explicit name falls back to the derived last-segment identity.
    assert ("plain", "1.0.0") in identities
    # Workspace links and the project root are disclosed, never silently dropped.
    assert web.excluded == [
        {"spec": "", "reason": "project-package", "name": "eurogas-nexus-web"},
        {
            "spec": "node_modules/linked",
            "reason": "workspace-link",
            "name": "linked",
            "resolved": "packages/linked",
        },
    ]
    # Nested installs resolve to the package name, never to the nested path.
    assert all("node_modules" not in item["name"] for item in web.packages)
    assert sum(1 for item in web.packages if item["name"] == "dup") == 2

    purls = {(item["name"], item["version"]): item["purl"] for item in web.packages}
    assert purls[("@scope/tool", "2.0.0")] == "pkg:npm/%40scope/tool@2.0.0"
    assert purls[("dup", "1.0.0")] == "pkg:npm/dup@1.0.0"
    assert purls[("real-package", "3.0.0")] == "pkg:npm/real-package@3.0.0"


def test_purl_encoding_and_ecosystem_identity_rules() -> None:
    # npm names are lowercased but underscores are not rewritten.
    assert generate_sboms.build_purl("npm", "UPPER_Case", "1.0.0") == "pkg:npm/upper_case@1.0.0"
    # Cargo crate names keep their case and underscores; '+' is percent-encoded.
    assert (
        generate_sboms.build_purl("cargo", "MixedCase_Crate", "2.0.0+meta")
        == "pkg:cargo/MixedCase_Crate@2.0.0%2Bmeta"
    )
    # PyPI names use the PEP 503 canonical form: every [-_.] run collapses to '-'.
    assert (
        generate_sboms.build_purl("pypi", "My_Package.Name", "1.0rc1")
        == "pkg:pypi/my-package-name@1.0rc1"
    )
    assert generate_sboms.build_purl("pypi", "a-_.-B", "1.0") == "pkg:pypi/a-b@1.0"
    assert (
        generate_sboms.build_purl("pypi", "typing_extensions", "4.16.0")
        == "pkg:pypi/typing-extensions@4.16.0"
    )
    # npm scopes become a namespace that is lowercased and percent-encoded.
    assert (
        generate_sboms.build_purl("npm", "pkg", "1.0.0", namespace="@Scope")
        == "pkg:npm/%40scope/pkg@1.0.0"
    )
    # Structured quoting encodes separators instead of letting them through.
    assert generate_sboms.build_purl("npm", "odd/name", "1.0.0") == "pkg:npm/odd%2Fname@1.0.0"
    assert generate_sboms.build_purl("npm", "pkg", "1.0.0?a=b#c") == "pkg:npm/pkg@1.0.0%3Fa%3Db%23c"


def test_pypi_canonicalization_matches_installed_packaging() -> None:
    """Cross-check the PEP 503 rule against the upstream implementation."""
    packaging_utils = pytest.importorskip("packaging.utils")
