def test_malformed_and_empty_required_inputs_are_rejected(tmp_path: Path) -> None:
    bad_json = minimal_tree(tmp_path / "bad-json")
    (bad_json / "clients/web/package-lock.json").write_text("{not json", encoding="utf-8")
    with pytest.raises(generate_sboms.SbomInputError) as json_error:
        generate_sboms.collect_components(root=bad_json)
    assert "invalid JSON" in str(json_error.value)

    bad_toml = minimal_tree(tmp_path / "bad-toml")
    (bad_toml / "clients/desktop/src-tauri/Cargo.lock").write_text(
        "[[package]\nname = ", encoding="utf-8"
    )
    with pytest.raises(generate_sboms.SbomInputError) as toml_error:
        generate_sboms.collect_components(root=bad_toml)
    assert "invalid TOML" in str(toml_error.value)

    zero_byte = minimal_tree(tmp_path / "zero-byte")
    (zero_byte / "clients/desktop/package-lock.json").write_text("", encoding="utf-8")
    with pytest.raises(generate_sboms.SbomInputError) as empty_error:
        generate_sboms.collect_components(root=zero_byte)
    assert "invalid JSON" in str(empty_error.value)

    no_npm_packages = minimal_tree(tmp_path / "empty-npm")
    write_npm_lock(
        no_npm_packages / "clients/web/package-lock.json",
        {"": {"name": "eurogas-nexus-web", "version": "0.5.0"}},
    )
    with pytest.raises(generate_sboms.SbomInputError) as npm_error:
        generate_sboms.collect_components(root=no_npm_packages)
    assert "no third-party packages" in str(npm_error.value)

    no_cargo_array = minimal_tree(tmp_path / "empty-cargo")
    (no_cargo_array / "clients/desktop/src-tauri/Cargo.lock").write_text(
        "version = 4\n", encoding="utf-8"
    )
    with pytest.raises(generate_sboms.SbomInputError) as cargo_error:
        generate_sboms.collect_components(root=no_cargo_array)
    assert "missing 'package' array" in str(cargo_error.value)

    no_python_packages = minimal_tree(tmp_path / "empty-python")
    (no_python_packages / "requirements-runtime.lock").write_text(
        "eurogas-nexus==0.5.0 \\\n    --hash=sha256:" + "0" * 64 + "\n", encoding="utf-8"
    )
    with pytest.raises(generate_sboms.SbomInputError) as python_error:
        generate_sboms.collect_components(root=no_python_packages)
    assert "no third-party packages" in str(python_error.value)

    bad_identity = minimal_tree(tmp_path / "bad-identity")
    write_npm_lock(
        bad_identity / "clients/web/package-lock.json",
        {"node_modules/bad name": {"version": "1.0.0"}},
    )
    with pytest.raises(generate_sboms.SbomInputError) as identity_error:
        generate_sboms.collect_components(root=bad_identity)
    assert "cannot resolve npm package identity" in str(identity_error.value)


