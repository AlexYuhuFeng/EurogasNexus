#!/usr/bin/env python3
"""Build the shipped NW Europe heating-degree-day reference from Eurostat (no key).

Writes ``src/eurogas_nexus/reference_data/nwe_hdd_eurostat.json``: monthly heating degree
days per NWE country (Eurostat ``nrg_chdd_m``, JRC method: HDD = 18 °C − Tm on a day whose
mean temperature Tm is at or below 15 °C, else 0), and each country's weight in the region
(its households' and commercial/public services' gas use, Eurostat ``nrg_cb_gas``
``FC_OTH_HH_E`` + ``FC_OTH_CP_E``, TJ GCV, mean of 2015-2019: the last five years Eurostat
publishes for every NWE country including the UK). The forward balance reads this file;
it is regenerated by hand when Eurostat publishes a new year, and the diff is reviewed.

Licence: Eurostat data, © European Union, reuse including commercial reuse authorised
under CC BY 4.0 with the source acknowledged (docs/legal/DATA_SOURCE_TERMS.md).

    python scripts/ops/build_hdd_reference.py            # fetch and write
    python scripts/ops/build_hdd_reference.py --check    # fetch and compare, write nothing
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "eurogas_nexus" / "reference_data" / "nwe_hdd_eurostat.json"
API = "https://ec.europa.eu/eurostat/api/dissemination/statistics/1.0/data/"
#: Eurostat's geo code per balance-region country (Eurostat writes the UK as UK).
COUNTRIES = {"GB": "UK", "NL": "NL", "BE": "BE", "DE": "DE", "FR": "FR", "DK": "DK", "LU": "LU"}
FIRST_MONTH = "1996-01"
WEIGHT_YEARS = ("2015", "2016", "2017", "2018", "2019")


def _get(dataset: str, params: list[tuple[str, str]]) -> dict:
    pairs = [("format", "JSON"), ("lang", "en"), *params]
    query = "&".join(f"{key}={value}" for key, value in pairs)
    request = urllib.request.Request(
        f"{API}{dataset}?{query}", headers={"User-Agent": "eurogas-nexus-reference-build"}
    )
    with urllib.request.urlopen(request, timeout=120) as response:  # noqa: S310 (fixed host)
        return json.loads(response.read())


def _cells(payload: dict) -> list[tuple[dict[str, str], float]]:
    """Eurostat JSON-stat as (coordinates, value) pairs."""

    dims, sizes = payload["id"], payload["size"]
    inverse = {
        dim: {pos: code for code, pos in payload["dimension"][dim]["category"]["index"].items()}
        for dim in dims
    }
    cells = []
    for flat, value in payload["value"].items():
        index, coords = int(flat), {}
        for dim, size in zip(reversed(dims), reversed(sizes), strict=True):
            coords[dim] = inverse[dim][index % size]
            index //= size
        cells.append((coords, float(value)))
    return cells


def build() -> dict:
    geos = [("geo", code) for code in COUNTRIES.values()]
    hdd_payload = _get(
        "nrg_chdd_m",
        [("indic_nrg", "HDD"), ("unit", "NR"), *geos, ("sinceTimePeriod", FIRST_MONTH)],
    )
    use_payload = _get(
        "nrg_cb_gas",
        [("unit", "TJ_GCV"), ("siec", "G3000"), ("nrg_bal", "FC_OTH_HH_E"),
         ("nrg_bal", "FC_OTH_CP_E"), *geos, *[("time", year) for year in WEIGHT_YEARS]],
    )
    back = {eurostat: ours for ours, eurostat in COUNTRIES.items()}
    monthly: dict[str, dict[str, float]] = {ours: {} for ours in COUNTRIES}
    for coords, value in _cells(hdd_payload):
        monthly[back[coords["geo"]]][coords["time"]] = round(value, 2)
    use: dict[str, list[float]] = {ours: [] for ours in COUNTRIES}
    for coords, value in _cells(use_payload):
        use[back[coords["geo"]]].append(value)
    expected = 2 * len(WEIGHT_YEARS)
    missing = [code for code, values in use.items() if len(values) != expected]
    if missing:
        raise SystemExit(f"Eurostat gas use incomplete for {missing}")
    totals = {code: sum(values) / len(WEIGHT_YEARS) for code, values in use.items()}
    weights = {code: round(total / sum(totals.values()), 6) for code, total in totals.items()}
    months = sorted(set.intersection(*(set(values) for values in monthly.values())))
    return {
        "schema": "eurogas-nexus/hdd-reference/1",
        "region": "NWE",
        "countries": list(COUNTRIES),
        "method": (
            "Eurostat nrg_chdd_m (JRC): a day's HDD is 18 °C minus its mean temperature when "
            "that is at or below 15 °C, else 0; monthly sums. The region's HDD is the "
            "countries' HDD weighted by their households' and commercial/public services' "
            "gas use (nrg_cb_gas FC_OTH_HH_E + FC_OTH_CP_E, TJ GCV, mean 2015-2019)."
        ),
        "attribution": "Source: Eurostat (nrg_chdd_m, nrg_cb_gas), © European Union",
        "licence": "CC BY 4.0",
        "eurostat_updated": {
            "nrg_chdd_m": hdd_payload.get("updated"),
            "nrg_cb_gas": use_payload.get("updated"),
        },
        "built_at_utc": datetime.now(UTC).replace(microsecond=0).isoformat(),
        "weights": weights,
        "weight_basis_tj_gcv_per_year": {code: round(total) for code, total in totals.items()},
        "months": months,
        "monthly_hdd": {code: [monthly[code][month] for month in months] for code in COUNTRIES},
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare with the shipped file")
    args = parser.parse_args(argv)
    built = build()
    if args.check:
        shipped = json.loads(OUT.read_text(encoding="utf-8"))
        same = {k: shipped.get(k) == built[k] for k in ("weights", "months", "monthly_hdd")}
        print(json.dumps(same, indent=2))
        return 0 if all(same.values()) else 1
    OUT.write_text(json.dumps(built, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    months = len(built["months"])
    print(f"wrote {OUT.relative_to(ROOT)}: {months} months, weights {built['weights']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
