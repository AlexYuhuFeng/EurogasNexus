def source_line(section: str | None, simulated: bool) -> str:
    """The source line under an exhibit of ``section``, in the report's language."""

    from eurogas_nexus.application.reports.lang import zh

    if simulated:
        return DEMO_SOURCE_ZH if zh() else DEMO_SOURCE
    if section is None:
        return "Eurogas Nexus 计算。" if zh() else "Eurogas Nexus."
    return (SOURCE_LINES_ZH if zh() else SOURCE_LINES)[section]


# --------------------------------------------------------------------------- helpers


def iso(day: date | str) -> str:
    return day if isinstance(day, str) else day.isoformat()


def as_day(value: date | str) -> date:
    return value if isinstance(value, date) else date.fromisoformat(str(value)[:10])


def same_day_last_year(day: date) -> date:
    try:
        return day.replace(year=day.year - 1)
    except ValueError:
        return day - timedelta(days=365)


def recent_variation(series: dict[date, float], until: date, days: int = 30) -> float | None:
    """Standard deviation of consecutive daily changes over ``days`` up to ``until``."""

    keys = sorted(d for d in series if until - timedelta(days=days) <= d <= until)
    diffs = [series[b] - series[a] for a, b in zip(keys, keys[1:], strict=False)
             if (b - a).days == 1]
    if len(diffs) < 5:
        return None
    mean = sum(diffs) / len(diffs)
    variance = sum((x - mean) ** 2 for x in diffs) / (len(diffs) - 1)
    return math.sqrt(variance) or None


def change_at(series: dict[date, float], day: date, back: int, tolerance: int = 0):
    """``series[day] - series[day - back]`` (nearest earlier within ``tolerance``)."""

    if day not in series:
        return None
    for extra in range(tolerance + 1):
        prior = day - timedelta(days=back + extra)
        if prior in series:
            return series[day] - series[prior]
    return None


def years_held(series: dict[date, Any], latest: date) -> int:
    """Whole prior years with data on the same day (±3 days), for "range of N years"."""

    count = 0
    for years in range(1, 6):
        try:
            target = latest.replace(year=latest.year - years)
        except ValueError:
            target = latest - timedelta(days=365 * years)
        if any(abs((d - target).days) <= 3 for d in series):
            count += 1
        else:
            break
    return count


def materiality(change: float | None, variation: float | None) -> tuple[float, str]:
    if change is None:
        return 0.0, "no comparable earlier value held"
    if not variation:
        return min(abs(change) and 1.0, 1.0), "recent variation not measurable"
    z = abs(change) / variation
    return round(z, 2), f"change {z:.1f}x the standard deviation of daily changes over 30 days"


def fact(
    key: str,
    section: str,
    label: str,
    value: float | None,
    unit: str,
    *,
    day: str,
    state: str,
    simulated: bool = False,
    sentence: str,
    headline: str = "",
    score: float = 0.0,
    reason: str = "",
    dod: float | None = None,
    wow: float | None = None,
    yoy: float | None = None,
    change_unit: str | None = None,
    years: int = 0,
    implications: list[str] | None = None,
    forecast: str | None = None,
    scheduled: bool = False,
    spark: list[float | None] | None = None,
    exhibits: list[str] | None = None,
    sources: list[str] | None = None,
    indicator: bool = True,
    related: list[str] | None = None,
) -> dict[str, Any]:
    unit_c = change_unit or unit
    phrases = []
    if value is not None:
        phrases.append(rules.number(value, unit))
    from eurogas_nexus.application.reports.lang import zh

    if zh():
        if dod is not None:
            phrases.append(f"较前一日{rules.move(dod, unit_c)}")
        if wow is not None:
            phrases.append(f"较一周前{rules.move(wow, unit_c)}")
        if yoy is not None:
            size = rules.number(abs(yoy), "", 1) + "个百分点" if unit_c == "points" else \
                rules.number(abs(yoy), unit_c)
            phrases.append(f"较一年前{'高' if yoy > 0 else '低'}{size}")
    else:
        if dod is not None:
            phrases.append(f"{rules.move(dod, unit_c)} on the day")
        if wow is not None:
            phrases.append(f"{rules.move(wow, unit_c)} on the week")
        if yoy is not None:
            side = "above" if yoy > 0 else "below"
            size = rules.number(abs(yoy), "", 1) + " points" if unit_c == "points" else \
                rules.number(abs(yoy), unit_c)
            phrases.append(f"{size} {side} a year earlier")
    return {
        "key": key,
        "section": section,
        #: The fact's figures as the desk writes them (what any text citing it may say).
        "phrases": phrases,
        "label": label,
        "value": None if value is None else round(value, 4),
        "unit": unit,
        "day": day,
        "state": state,
        "simulated": simulated,
        "forecast": forecast,
        "scheduled": scheduled,
        "comparisons": {
            "day": None if dod is None else round(dod, 4),
            "week": None if wow is None else round(wow, 4),
            "year": None if yoy is None else round(yoy, 4),
            "norm": None,
            "unit": change_unit or unit,
            "years_held": years,
        },
        "score": round(score, 2),
        "reason": reason,
        "sentence": sentence,
        "headline": headline or sentence,
        "implications": implications or [],
        "spark": spark or [],
        "exhibits": exhibits or [],
        "sources": sources or [],
        "indicator": indicator,
        "related": related or [],
    }


def series_points(series: dict[date, float], first: date, last: date) -> list[list]:
    return [[iso(d), round(series[d], 2)] for d in sorted(series) if first <= d <= last]


def shifted_year(series: dict[date, float], first: date, last: date) -> list[list]:
    """The same days a year earlier, placed on this year's dates (context line)."""

    out = []
    day = first
    while day <= last:
        prior = same_day_last_year(day)
        if prior in series:
            out.append([iso(day), round(series[prior], 2)])
        day += timedelta(days=1)
    return out


def spark_of(series: dict[date, float], last: date, days: int = 30) -> list[float | None]:
    return [round(series[d], 2) if d in series else None
            for d in (last - timedelta(days=days - 1 - i) for i in range(days))]


def default_window(kind: str, family: str) -> str:
    """The window an exhibit opens on, by report kind (the house standard)."""

    if family == "storage":
        return "gas_year"
    if kind == "weekly":
        return "91d"
    if kind == "monthly":
        return "395d"
    if family == "price":
        return "365d"
    return "30d"


def exhibit(
    exhibit_id: str,
    section: str,
    kind: str,
    *,
    title: str,
    subtitle: str,
    unit: str,
    series: list[dict],
    types: tuple[str, ...],
    windows: tuple[str, ...],
    window: str,
    simulated: bool,
    notes: str = "",
    reference_lines: list[dict] | None = None,
    half: bool = False,
) -> dict[str, Any]:
    return {
        "id": exhibit_id,
        "section": section,
        "type": kind,
        "types": list(types),
        "title": title,
        "subtitle": subtitle,
        "unit": unit,
        "series": series,
        "windows": list(windows),
        "window": window,
        "source": source_line(section if section in SOURCE_LINES else None, simulated),
        "notes": notes,
        "reference_lines": reference_lines or [],
        "half": half,
    }


def table(caption: str, columns: list[tuple[str, str, str]], rows: list[dict], *,
          source: str = "", notes: str = "") -> dict:
    return {
        "caption": caption,
        "columns": [{"key": k, "label": label, "kind": kind} for k, label, kind in columns],
        "rows": rows,
        "source": source,
        "notes": notes,
    }


def window_start(window: str, end: date) -> date:
    if window == "gas_year":
        start_year = end.year if end.month >= 10 else end.year - 1
        return date(start_year, 10, 1)
    return end - timedelta(days=WINDOWS.get(window, 30) - 1)


def sign_word(value: float | None, up: str = "up", down: str = "down") -> str:
    if value is None or abs(value) < 1e-9:
        return "unchanged"
    return up if value > 0 else down


