"""The fact sheet: every candidate fact a report may present, with its comparisons and weight.

Section adapters (``sections.py``) read the data; this module turns what they read into the
publication's raw material, the same way for every report kind:

- **facts**: one per indicator and per event, with a stable key, value, unit, the comparisons
  the held data supports (day, week, year; "vs norm" only where a norm is held), the number of
  prior years held, a materiality score with the rule that produced it, its state (current,
  late, stale; simulated; forecast with its method), the rule sentence that states it, the
  implications the engine can derive from it, and the exhibits that can show it;
- **exhibits**: numbered figures with a declarative title, a subtitle (measure, unit, window),
  a source line and notes, each with the chart types and windows it permits; the series cover
  the longest permitted window and the renderer cuts the chosen one;
- **edited tables** for the body (at most :data:`BODY_ROWS` rows) and the full series for the
  data annex;
- the section's **prose**: a lead sentence and a short paragraph assembled from its facts.

Materiality is transparent: a change is weighed against the indicator's own recent variation
(the standard deviation of its daily changes over the last 30 days held), a level against a
year earlier, an event by the capacity it removes against the supply it affects, a forecast by
the size of the change it projects. The score and its reason are stored with each fact.

Pure computation over what the adapters read: no query, no model.
"""

